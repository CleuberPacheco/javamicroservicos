-- ===================================================================
-- MIGRACAO V1: CRIACAO DE SEQUENCES E TABELAS (ORACLE DATABASE)
-- Tema 1: Eficiencia Energetica e Sustentabilidade
-- ===================================================================

CREATE SEQUENCE SEQ_TB_USUARIO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TB_SETOR START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TB_EQUIPAMENTO_IOT START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TB_LEITURA_CONSUMO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_TB_ALERTA_EFICIENCIA START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- 1. Tabela de Usuarios (Autenticacao e Autorizacao via Spring Security)
CREATE TABLE TB_USUARIO (
    ID_USUARIO NUMBER(19) DEFAULT SEQ_TB_USUARIO.NEXTVAL NOT NULL,
    NOME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(120) NOT NULL,
    SENHA VARCHAR2(255) NOT NULL,
    ROLE VARCHAR2(30) NOT NULL,
    DATA_CRIACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_TB_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_TB_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_TB_USUARIO_ROLE CHECK (ROLE IN ('ADMIN', 'OPERADOR', 'AUDITOR'))
);

-- 2. Tabela de Setores / Unidades Monitoradas
CREATE TABLE TB_SETOR (
    ID_SETOR NUMBER(19) DEFAULT SEQ_TB_SETOR.NEXTVAL NOT NULL,
    NOME VARCHAR2(100) NOT NULL,
    LOCALIZACAO VARCHAR2(150) NOT NULL,
    RESPONSAVEL VARCHAR2(100) NOT NULL,
    LIMITE_MENSAL_KWH NUMBER(12, 2) NOT NULL,
    LIMITE_DIARIO_KWH NUMBER(12, 2) NOT NULL,
    ATIVO NUMBER(1) DEFAULT 1 NOT NULL,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_TB_SETOR PRIMARY KEY (ID_SETOR),
    CONSTRAINT CK_TB_SETOR_ATIVO CHECK (ATIVO IN (0, 1))
);

-- 3. Tabela de Equipamentos e Sensores IoT
CREATE TABLE TB_EQUIPAMENTO_IOT (
    ID_EQUIPAMENTO NUMBER(19) DEFAULT SEQ_TB_EQUIPAMENTO_IOT.NEXTVAL NOT NULL,
    ID_SETOR NUMBER(19) NOT NULL,
    CODIGO_SENSOR VARCHAR2(50) NOT NULL,
    NOME VARCHAR2(120) NOT NULL,
    TIPO_EQUIPAMENTO VARCHAR2(60) NOT NULL,
    POTENCIA_WATTS NUMBER(10, 2) NOT NULL,
    LIMITE_CONSUMO_HORA_KWH NUMBER(10, 2) NOT NULL,
    STATUS_OPERACIONAL VARCHAR2(30) DEFAULT 'LIGADO' NOT NULL,
    DESLIGAMENTO_AUTOMATICO NUMBER(1) DEFAULT 1 NOT NULL,
    ULTIMA_ATUALIZACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT PK_TB_EQUIPAMENTO_IOT PRIMARY KEY (ID_EQUIPAMENTO),
    CONSTRAINT UK_TB_EQUIP_CODIGO_SENSOR UNIQUE (CODIGO_SENSOR),
    CONSTRAINT FK_TB_EQUIP_SETOR FOREIGN KEY (ID_SETOR) REFERENCES TB_SETOR (ID_SETOR),
    CONSTRAINT CK_TB_EQUIP_STATUS CHECK (STATUS_OPERACIONAL IN ('LIGADO', 'DESLIGADO', 'EM_MANUTENCAO')),
    CONSTRAINT CK_TB_EQUIP_AUTO_OFF CHECK (DESLIGAMENTO_AUTOMATICO IN (0, 1))
);

-- 4. Tabela de Leituras de Consumo Energetico
CREATE TABLE TB_LEITURA_CONSUMO (
    ID_LEITURA NUMBER(19) DEFAULT SEQ_TB_LEITURA_CONSUMO.NEXTVAL NOT NULL,
    ID_EQUIPAMENTO NUMBER(19) NOT NULL,
    CONSUMO_KWH NUMBER(10, 3) NOT NULL,
    TEMPO_OCIOSO_MINUTOS NUMBER(10) DEFAULT 0 NOT NULL,
    ULTRAPASSOU_LIMITE NUMBER(1) DEFAULT 0 NOT NULL,
    DESLIGADO_AUTOMATICAMENTE NUMBER(1) DEFAULT 0 NOT NULL,
    DATA_HORA_LEITURA TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    OBSERVACAO VARCHAR2(255),
    CONSTRAINT PK_TB_LEITURA_CONSUMO PRIMARY KEY (ID_LEITURA),
    CONSTRAINT FK_TB_LEITURA_EQUIP FOREIGN KEY (ID_EQUIPAMENTO) REFERENCES TB_EQUIPAMENTO_IOT (ID_EQUIPAMENTO),
    CONSTRAINT CK_TB_LEITURA_LIMITE CHECK (ULTRAPASSOU_LIMITE IN (0, 1)),
    CONSTRAINT CK_TB_LEITURA_DESL_AUTO CHECK (DESLIGADO_AUTOMATICAMENTE IN (0, 1))
);

-- 5. Tabela de Alertas Automaticos de Eficiencia Energetica
CREATE TABLE TB_ALERTA_EFICIENCIA (
    ID_ALERTA NUMBER(19) DEFAULT SEQ_TB_ALERTA_EFICIENCIA.NEXTVAL NOT NULL,
    ID_SETOR NUMBER(19) NOT NULL,
    ID_EQUIPAMENTO NUMBER(19),
    ID_LEITURA NUMBER(19),
    TIPO_ALERTA VARCHAR2(60) NOT NULL,
    SEVERIDADE VARCHAR2(20) NOT NULL,
    MENSAGEM VARCHAR2(400) NOT NULL,
    ACAO_AUTOMATICA_EXECUTADA VARCHAR2(255),
    STATUS_ALERTA VARCHAR2(20) DEFAULT 'ABERTO' NOT NULL,
    DATA_GERACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DATA_RESOLUCAO TIMESTAMP,
    CONSTRAINT PK_TB_ALERTA_EFICIENCIA PRIMARY KEY (ID_ALERTA),
    CONSTRAINT FK_TB_ALERTA_SETOR FOREIGN KEY (ID_SETOR) REFERENCES TB_SETOR (ID_SETOR),
    CONSTRAINT FK_TB_ALERTA_EQUIP FOREIGN KEY (ID_EQUIPAMENTO) REFERENCES TB_EQUIPAMENTO_IOT (ID_EQUIPAMENTO),
    CONSTRAINT FK_TB_ALERTA_LEITURA FOREIGN KEY (ID_LEITURA) REFERENCES TB_LEITURA_CONSUMO (ID_LEITURA),
    CONSTRAINT CK_TB_ALERTA_SEVERIDADE CHECK (SEVERIDADE IN ('BAIXA', 'MEDIA', 'ALTA', 'CRITICA')),
    CONSTRAINT CK_TB_ALERTA_STATUS CHECK (STATUS_ALERTA IN ('ABERTO', 'RESOLVIDO'))
);

CREATE INDEX IDX_EQUIP_SETOR ON TB_EQUIPAMENTO_IOT (ID_SETOR);
CREATE INDEX IDX_LEITURA_EQUIP ON TB_LEITURA_CONSUMO (ID_EQUIPAMENTO);
CREATE INDEX IDX_ALERTA_STATUS ON TB_ALERTA_EFICIENCIA (STATUS_ALERTA);
